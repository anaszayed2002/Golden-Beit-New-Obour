create table public.nob_admin_phones (
  phone text primary key check (phone ~ '^20(10|11|12|15)[0-9]{8}$'),
  created_at timestamptz not null default now()
);
insert into public.nob_admin_phones (phone) values ('201040333703');

create table public.nob_listings (
  id bigint generated by default as identity (start with 101) primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  zone text not null check (zone in ('القادسية','الأمل')),
  area numeric(10,2) not null check (area > 0 and area < 100000),
  price bigint not null check (price > 0),
  paid bigint not null default 0 check (paid >= 0),
  remaining bigint not null default 0 check (remaining >= 0),
  ownership text not null check (ownership in ('مالك أصيل','توكيل')),
  ready boolean not null default false,
  description text not null default '' check (char_length(description) <= 2000),
  status text not null default 'pending' check (status in ('pending','approved','rejected','sold')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);
create index nob_listings_status_idx on public.nob_listings (status, created_at desc);
create index nob_listings_owner_idx on public.nob_listings (owner_id);

create table public.nob_listing_private (
  listing_id bigint primary key references public.nob_listings(id) on delete cascade,
  plot_number text check (char_length(plot_number) <= 40),
  contact_phone text not null check (contact_phone ~ '^01(0|1|2|5)[0-9]{8}$'),
  owner_name text not null,
  account_phone text not null
);

create table public.nob_plot_requests (
  id bigint generated always as identity primary key,
  listing_id bigint not null references public.nob_listings(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  phone text not null,
  handled boolean not null default false,
  created_at timestamptz not null default now(),
  unique (listing_id, user_id)
);
create index nob_plot_requests_user_idx on public.nob_plot_requests (user_id);

alter table public.nob_admin_phones enable row level security;
alter table public.nob_listings enable row level security;
alter table public.nob_listing_private enable row level security;
alter table public.nob_plot_requests enable row level security;

-- Only approved listings are public, and only their non-sensitive columns.
revoke all on public.nob_admin_phones, public.nob_listing_private, public.nob_plot_requests from anon, authenticated;
revoke all on public.nob_listings from anon, authenticated;
grant select (id, zone, area, price, paid, remaining, ownership, ready, description, status, created_at)
  on public.nob_listings to anon, authenticated;
create policy "nob approved listings are public" on public.nob_listings
  for select to anon, authenticated using (status = 'approved');

-- Account helpers: accounts use the shared phone-as-email format p20XXXXXXXXXX@phone.goldenbeit.com
create or replace function public.nob_me()
returns table (name text, phone text)
language sql stable security definer set search_path = ''
as $$
  select btrim(coalesce(u.raw_user_meta_data ->> 'full_name', '')),
         '0' || substring(lower(u.email) from '^p20([0-9]{10})@phone\.goldenbeit\.com$')
  from auth.users u where u.id = (select auth.uid());
$$;

create or replace function public.nob_is_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from auth.users u
    join public.nob_admin_phones a on a.phone = substring(lower(u.email) from '^p(20[0-9]{10})@phone\.goldenbeit\.com$')
    where u.id = (select auth.uid())
  );
$$;

create or replace function public.nob_submit_listing(
  p_zone text, p_plot_number text, p_area numeric, p_ownership text, p_ready boolean,
  p_price bigint, p_paid bigint, p_remaining bigint, p_contact_phone text, p_description text)
returns bigint
language plpgsql security definer set search_path = ''
as $$
declare v_id bigint; v_me record;
begin
  if (select auth.uid()) is null then raise exception 'not_signed_in' using errcode = '42501'; end if;
  select * into v_me from public.nob_me();
  if (select count(*) from public.nob_listings where owner_id = (select auth.uid()) and status = 'pending') >= 10 then
    raise exception 'too_many_pending' using errcode = '22023';
  end if;
  insert into public.nob_listings (owner_id, zone, area, price, paid, remaining, ownership, ready, description)
  values ((select auth.uid()), p_zone, p_area, p_price, coalesce(p_paid,0), coalesce(p_remaining,0), p_ownership,
          coalesce(p_ready,false), btrim(coalesce(p_description,'')))
  returning id into v_id;
  insert into public.nob_listing_private (listing_id, plot_number, contact_phone, owner_name, account_phone)
  values (v_id, nullif(btrim(coalesce(p_plot_number,'')), ''), btrim(p_contact_phone), v_me.name, coalesce(v_me.phone,''));
  return v_id;
end $$;

create or replace function public.nob_request_plot(p_listing_id bigint)
returns void
language plpgsql security definer set search_path = ''
as $$
declare v_me record;
begin
  if (select auth.uid()) is null then raise exception 'not_signed_in' using errcode = '42501'; end if;
  if not exists (select 1 from public.nob_listings where id = p_listing_id and status = 'approved') then
    raise exception 'listing_not_found' using errcode = '22023';
  end if;
  select * into v_me from public.nob_me();
  insert into public.nob_plot_requests (listing_id, user_id, name, phone)
  values (p_listing_id, (select auth.uid()), v_me.name, coalesce(v_me.phone,''))
  on conflict (listing_id, user_id) do update set created_at = now(), handled = false;
end $$;

-- Admin-only views of everything, including phones and plot numbers.
create or replace function public.nob_admin_listings()
returns table (id bigint, zone text, area numeric, price bigint, paid bigint, remaining bigint, ownership text,
  ready boolean, description text, status text, created_at timestamptz, plot_number text, contact_phone text,
  owner_name text, account_phone text, request_count bigint)
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.nob_is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  return query
    select l.id, l.zone, l.area, l.price, l.paid, l.remaining, l.ownership, l.ready, l.description, l.status, l.created_at,
           p.plot_number, p.contact_phone, p.owner_name, p.account_phone,
           (select count(*) from public.nob_plot_requests r where r.listing_id = l.id)
    from public.nob_listings l join public.nob_listing_private p on p.listing_id = l.id
    order by l.created_at desc;
end $$;

create or replace function public.nob_admin_requests()
returns table (id bigint, listing_id bigint, name text, phone text, handled boolean, created_at timestamptz,
  zone text, area numeric, price bigint, plot_number text, owner_name text, contact_phone text)
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.nob_is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  return query
    select r.id, r.listing_id, r.name, r.phone, r.handled, r.created_at, l.zone, l.area, l.price,
           p.plot_number, p.owner_name, p.contact_phone
    from public.nob_plot_requests r
    join public.nob_listings l on l.id = r.listing_id
    join public.nob_listing_private p on p.listing_id = l.id
    order by r.handled, r.created_at desc;
end $$;

create or replace function public.nob_admin_set_status(p_listing_id bigint, p_status text)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.nob_is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  update public.nob_listings set status = p_status, reviewed_at = now() where id = p_listing_id;
end $$;

create or replace function public.nob_admin_set_handled(p_request_id bigint, p_handled boolean)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.nob_is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  update public.nob_plot_requests set handled = p_handled where id = p_request_id;
end $$;

